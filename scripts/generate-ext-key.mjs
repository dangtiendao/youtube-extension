import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const secretsDir = path.join(rootDir, '.secrets');
const keyFile = path.join(secretsDir, 'extension-key.json');

/**
 * Chrome calculates an unpacked extension ID from the SHA-256 hash of the DER-encoded
 * SubjectPublicKeyInfo (base64 value in manifest.json "key"):
 * take first 16 bytes (32 hex chars) and map hex 0..f -> ASCII 'a'..'p'.
 */
function computeChromeExtensionId(publicKeyDer) {
  const hash = crypto.createHash('sha256').update(publicKeyDer).digest('hex').slice(0, 32);
  let id = '';
  for (const ch of hash) {
    const nibble = parseInt(ch, 16);
    id += String.fromCharCode('a'.charCodeAt(0) + nibble);
  }
  return id;
}

function loadOrCreateKey() {
  if (fs.existsSync(keyFile)) {
    const existing = JSON.parse(fs.readFileSync(keyFile, 'utf8'));
    if (existing.publicKeyBase64 && existing.extensionId) {
      return existing;
    }
  }

  fs.mkdirSync(secretsDir, { recursive: true });

  const { publicKey, privateKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: { type: 'spki', format: 'der' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });

  const publicKeyBase64 = publicKey.toString('base64');
  const extensionId = computeChromeExtensionId(publicKey);

  const data = {
    extensionId,
    publicKeyBase64,
    privateKeyPem: privateKey,
    createdAt: new Date().toISOString(),
  };

  fs.writeFileSync(keyFile, JSON.stringify(data, null, 2), 'utf8');
  return data;
}

const keyInfo = loadOrCreateKey();

// Write generated TypeScript constant into packages/shared so Engine & Extension share the exact fixed Extension ID
const sharedGeneratedPath = path.join(rootDir, 'packages', 'shared', 'src', 'extension-id.generated.ts');
fs.mkdirSync(path.dirname(sharedGeneratedPath), { recursive: true });
fs.writeFileSync(
  sharedGeneratedPath,
  `// Auto-generated by scripts/generate-ext-key.mjs — DO NOT EDIT MANUALLY\n` +
    `export const FIXED_EXTENSION_ID = '${keyInfo.extensionId}';\n` +
    `export const FIXED_EXTENSION_ORIGIN = 'chrome-extension://${keyInfo.extensionId}';\n`,
  'utf8'
);

// Also write public-only metadata file for extension build & installer scripts
const publicKeyMetaPath = path.join(rootDir, 'packages', 'extension', 'extension-key.public.json');
fs.mkdirSync(path.dirname(publicKeyMetaPath), { recursive: true });
fs.writeFileSync(
  publicKeyMetaPath,
  JSON.stringify(
    {
      extensionId: keyInfo.extensionId,
      publicKeyBase64: keyInfo.publicKeyBase64,
    },
    null,
    2
  ),
  'utf8'
);

console.log(`[TubeVault] Fixed Extension ID: ${keyInfo.extensionId}`);
